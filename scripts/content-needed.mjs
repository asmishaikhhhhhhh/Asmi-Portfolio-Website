// Lists every needed("…") placeholder and `needs:` note in /data → docs/05-content-needed.md
// Run: npm run needed
import fs from "node:fs";
import path from "node:path";

const files = [
  ...fs.readdirSync("data/projects").filter((f) => f.endsWith(".ts") && f !== "index.ts").map((f) => `data/projects/${f}`),
  "data/portfolio.ts",
  "data/playground.ts",
];
const out = ["# Content needed from Asmi", "", "Generated by `npm run needed` from every `needed(\"…\")` placeholder in /data. Fill these in the data files; the dev site shows each one as a dashed box.", ""];
let total = 0;
for (const f of files) {
  const src = fs.readFileSync(f, "utf8");
  const items = [
    ...[...src.matchAll(/needed\(\s*(["'`])([\s\S]*?)\1\s*\)/g)].map((m) => m[2]),
    ...[...src.matchAll(/needs:\s*(["'`])([\s\S]*?)\1/g)].map((m) => m[2]),
  ];
  // `type: "needed"` blocks
  for (const m of src.matchAll(/type:\s*"needed",\s*items:\s*\[([\s\S]*?)\]/g)) {
    items.push(...[...m[1].matchAll(/(["'`])([\s\S]*?)\1/g)].map((x) => x[2]));
  }
  const uniq = [...new Set(items.map((s) => s.replace(/\s+/g, " ").trim()))];
  if (!uniq.length) continue;
  total += uniq.length;
  out.push(`## ${path.basename(f, ".ts")} (${uniq.length})`, "", ...uniq.map((s) => `- [ ] ${s}`), "");
}
fs.writeFileSync("docs/05-content-needed.md", out.join("\n"));
console.log(`content-needed: ${total} items → docs/05-content-needed.md`);
